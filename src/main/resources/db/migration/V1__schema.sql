-- Table names are plural throughout. "transaction" is a keyword in enough dialects
-- that singular would have to be quoted in some places and not others; one rule for
-- all six tables costs nothing and avoids the inconsistency.
--
-- Enumerated columns are varchar with a check constraint rather than native
-- PostgreSQL enum types: JPA maps them directly, and adding a value later is a
-- constraint change rather than a type migration.

create table categories (
    id   bigint generated by default as identity primary key,
    name varchar(50) not null unique,
    type varchar(10) not null,
    constraint chk_categories_type check (type in ('INCOME', 'EXPENSE'))
);

create table category_rules (
    id          bigint generated by default as identity primary key,
    keyword     varchar(100) not null,
    category_id bigint not null references categories (id),
    priority    int not null default 0,
    constraint chk_category_rules_keyword_not_blank check (length(trim(keyword)) > 0)
);

create index idx_category_rules_category on category_rules (category_id);

create table import_batches (
    id             bigint generated by default as identity primary key,
    file_name      varchar(255) not null,
    imported_at    timestamp with time zone not null default now(),
    total_rows     int not null,
    imported_rows  int not null,
    duplicate_rows int not null,
    rejected_rows  int not null,
    -- Every source line falls into exactly one bucket. The importer asserts this
    -- in a test; the database refuses to store a batch that violates it.
    constraint chk_import_batches_rows_add_up
        check (total_rows = imported_rows + duplicate_rows + rejected_rows)
);

create table import_errors (
    id              bigint generated by default as identity primary key,
    import_batch_id bigint not null references import_batches (id) on delete cascade,
    row_number      int not null,
    raw_line        text not null,
    reason          varchar(255) not null
);

create index idx_import_errors_batch on import_errors (import_batch_id);

create table transactions (
    id              bigint generated by default as identity primary key,
    date            date not null,
    description     varchar(255) not null,
    amount          numeric(12, 2) not null,
    currency        varchar(3) not null,
    amount_rsd      numeric(12, 2) not null,
    category_id     bigint references categories (id),
    source          varchar(10) not null,
    import_batch_id bigint references import_batches (id),
    fingerprint     varchar(64) unique,
    created_at      timestamp with time zone not null default now(),

    constraint chk_transactions_source check (source in ('MANUAL', 'IMPORT')),
    constraint chk_transactions_currency check (currency ~ '^[A-Z]{3}$'),
    constraint chk_transactions_description_not_blank check (length(trim(description)) > 0),

    -- ADR-0002: a transaction's income-or-expense nature is the sign of its amount,
    -- so zero has no nature and is refused here as well as in the request DTO.
    -- Conversion preserves the sign, so a zero dinar amount is equally impossible.
    constraint chk_transactions_amount_not_zero check (amount <> 0),
    constraint chk_transactions_amount_rsd_not_zero check (amount_rsd <> 0),

    -- ADR-0003: a fingerprint identifies an imported source line. Imported rows have
    -- one, manual rows do not, and nulls are distinct under the unique index, so two
    -- identical manual entries are allowed while a re-uploaded file is still caught.
    constraint chk_transactions_fingerprint_belongs_to_import
        check ((source = 'IMPORT') = (fingerprint is not null))
);

create index idx_transactions_date on transactions (date);
create index idx_transactions_category on transactions (category_id);
create index idx_transactions_batch on transactions (import_batch_id);

create table exchange_rates (
    id          bigint generated by default as identity primary key,
    currency    varchar(3) not null,
    rate_date   date not null,
    rate_to_rsd numeric(12, 4) not null,
    constraint uq_exchange_rates_currency_date unique (currency, rate_date),
    constraint chk_exchange_rates_currency check (currency ~ '^[A-Z]{3}$'),
    constraint chk_exchange_rates_positive check (rate_to_rsd > 0)
);

-- ADR-0005: the rate in force is the most recent one on or before a date, which is
-- the whole weekend-and-holiday rule. This index is the one that query rides on.
create index idx_exchange_rates_lookup on exchange_rates (currency, rate_date desc);
